#!/usr/bin/env python3
"""Convert the official visualizer's simple path-wait-path project to Pedro 3 Java.

Fail closed on unsupported features rather than silently discarding their behavior.
"""
import argparse
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEFAULT_PROJECT = ROOT / "paths/drive-pause-park.pp.json"
OUTPUT = ROOT / "TeamCode/src/main/java/org/firstinspires/ftc/teamcode/autonomous/DrivePauseParkRoute.java"


def number(value, label, low=None, high=None):
    if isinstance(value, bool) or not isinstance(value, (int, float)) or not math.isfinite(value):
        raise ValueError(f"{label} must be a finite number")
    if low is not None and value < low or high is not None and value > high:
        raise ValueError(f"{label} outside [{low}, {high}]")
    return format(value, ".12g")


def pose(point, heading):
    return "p.of({}, {}, {})".format(number(point["x"], "x", 0, 141.5),
                                      number(point["y"], "y", 0, 141.5),
                                      number(heading, "heading"))


def generate(doc):
    if doc.get("version") != "2.0.0":
        raise ValueError("Expected official visualizer project version 2.0.0; re-save in the current editor")
    lines = doc["lines"]
    seq = doc.get("sequence") or [{"kind": "path", "lineId": line["id"]} for line in lines]
    kinds = [s["kind"] for s in seq]
    if len(lines) != 2 or kinds not in (["path", "path"], ["path", "wait", "path"]):
        raise ValueError("Use exactly two atomic paths with one wait between them")
    path_steps = [s for s in seq if s["kind"] == "path"]
    by_id = {line["id"]: line for line in lines}
    if len(by_id) != 2 or path_steps[0]["lineId"] == path_steps[1]["lineId"]:
        raise ValueError("Paths must have distinct ids and each be used once")
    first = by_id[path_steps[0]["lineId"]]
    path_wait = first.get("waitAfterMs", first.get("waitAfter", {}).get("durationMs", 0))
    if len(seq) == 3 and path_wait:
        raise ValueError("Duplicate shooting waits: use a sequence wait OR the first path's wait, not both")
    wait_ms = float(number(seq[1]["durationMs"] if len(seq) == 3 else path_wait,
                           "shooting wait ms", 0, 30000))
    start = doc["startPoint"]
    previous = start
    previous_heading = float(number(start["headingDeg"], "starting heading"))
    methods = []
    for index, (method, step) in enumerate(zip(("toShoot", "toPark"), path_steps)):
        line = by_id[step["lineId"]]
        if line.get("kind") != "atomic" or line.get("throughPoints"):
            raise ValueError("Only atomic lines and Bezier control points are supported")
        if any(line.get(k) for k in ("waitBefore", "waitBeforeMs")) or (index == 1 and any(
                line.get(k) for k in ("waitAfterMs", "waitAfter"))):
            raise ValueError("Only a wait after the first path is supported")
        heading = line["heading"]
        if heading["type"] == "linear":
            a, b = heading["startDeg"], heading["endDeg"]
        elif heading["type"] == "constant":
            a = b = heading["degrees"]
        else:
            raise ValueError("Use constant or linear headings for this first routine")
        a, b = float(number(a, "start heading")), float(number(b, "end heading"))
        if abs((a - previous_heading + 180) % 360 - 180) > 1e-6:
            raise ValueError("Path heading must start at the previous pose heading")
        end = line["endPoint"]
        controls = line.get("controlPoints", [])
        points = [pose(previous, a)] + [pose(c, 0) for c in controls] + [pose(end, b)]
        if previous["x"] == end["x"] and previous["y"] == end["y"] and not controls:
            raise ValueError("A path must have nonzero length")
        call = "curve" if controls else "line"
        expression = f"Paths.{call}({', '.join(points)}).linear({pose(previous, a)}, {pose(end, b)})"
        methods.append(f"    public static Path {method}() {{\n        return {expression};\n    }}")
        previous, previous_heading = end, b
    return "\n".join([
        "package org.firstinspires.ftc.teamcode.autonomous;", "",
        "import com.pedropathing.api.Paths;", "import com.pedropathing.api.PoseFactory;",
        "import com.pedropathing.math.Pose;", "import com.pedropathing.paths.Path;", "",
        "/** Generated by tools/autonomous/generate_route.py. Edit the .pp.json visually, then regenerate. */",
        "public final class DrivePauseParkRoute {",
        "    private static final PoseFactory p = PoseFactory.degrees();",
        f"    public static final double SHOOTING_DELAY_SECONDS = {wait_ms / 1000:.12g};",
        "    private DrivePauseParkRoute() {}",
        f"    public static Pose start() {{ return {pose(start, start['headingDeg'])}; }}",
        *methods, "}", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("project", nargs="?", type=Path, default=DEFAULT_PROJECT)
    parser.add_argument("--check", action="store_true", help="Fail if committed Java is stale")
    args = parser.parse_args()
    try:
        code = generate(json.loads(args.project.read_text()))
        if args.check:
            if not OUTPUT.exists() or OUTPUT.read_text() != code:
                raise ValueError("Generated Java is stale; run generate_route.py")
        else:
            OUTPUT.write_text(code)
        print("Route Java matches visualizer project" if args.check else f"Generated {OUTPUT.relative_to(ROOT)}")
    except (ValueError, KeyError, TypeError) as error:
        parser.exit(2, f"Route rejected: {error}\n")


if __name__ == "__main__":
    main()
